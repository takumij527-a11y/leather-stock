items = []

def add(no, type_, name, level, structure, size, spec, memo, parts, patnote):
    items.append(dict(no=no, date="2026-11-24", type=type_, name=name, src="Pinterest（ユーザー保存）",
                      structure=structure, size=size, spec=spec, level=level, status="候補", memo=memo,
                      pattern=f"pat/{no}.svg", parts=parts, patnote=patnote))

