def fan(cx, by, bottom, top, h, sag):
    """ペーパーフィルターの平らな形：下辺 bottom、上辺の弦 top、高さ h、上辺は sag だけ外へふくらむ弧"""
    x1, x2 = cx - bottom / 2, cx + bottom / 2
    X1, X2 = cx - top / 2, cx + top / 2
    ty = by - h
    r = (top / 2) ** 2 / (2 * sag) + sag / 2
    return f"M{x1},{by} L{x2},{by} L{X2},{ty} A{r:.1f},{r:.1f} 0 0 0 {X1},{ty} Z"


