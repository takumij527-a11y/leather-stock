def circle(cx, cy, r): return f"M{cx-r},{cy} A{r},{r} 0 1 1 {cx+r},{cy} A{r},{r} 0 1 1 {cx-r},{cy} Z"

def flower(cx, cy, R, r, n=5, rot=-90):
    """n枚花びら（外周は円弧のつながり）"""
    pts = []
    for k in range(n):
        a0 = math.radians(rot + 360 * k / n - 180 / n); a1 = math.radians(rot + 360 * (k + 1) / n - 180 / n)
        pts.append(((cx + r * math.cos(a0), cy + r * math.sin(a0)), (cx + r * math.cos(a1), cy + r * math.sin(a1))))
    d = f"M{pts[0][0][0]:.1f},{pts[0][0][1]:.1f} "
    for (p0, p1) in pts:
        ar = r * math.sin(math.pi / n) * 1.05
        d += f"A{ar:.1f},{ar:.1f} 0 1 1 {p1[0]:.1f},{p1[1]:.1f} "
    return d + "Z"

