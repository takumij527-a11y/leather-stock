def tray(no, W, H, wall, name, size, memo):
    s = S(W, H)
    s.cut(rr(0, 0, W, H, 3))
    for a in [(0, wall, W, wall), (0, H-wall, W, H-wall), (wall, 0, wall, H), (W-wall, 0, W-wall, H)]: s.fold(*a)
    for (cx, cy, sx, sy) in [(0, 0, 1, 1), (W, 0, -1, 1), (0, H, 1, -1), (W, H, -1, -1)]:
        s.fold(cx, cy, cx + sx*wall, cy + sy*wall); s.hole(cx + sx*wall*0.35, cy + sy*wall*0.65, 2.5); s.hole(cx + sx*wall*0.65, cy + sy*wall*0.35, 2.5)
    s.text(W/2, H/2, "底", 1.0, bold=True)
    s.dim(0, 0, W, 0, str(W), -10); s.dim(W, 0, W, H, str(H), -10); s.dim(0, H, wall, H, str(wall), 10)
    s.save(P(no), f"仕上がり 底{W-2*wall}×{H-2*wall}×高さ{wall}（四隅をつまんでホック）")
    il = Ill(W, H*0.8)
    bw, bh = W - 2*wall, (H - 2*wall)*0.55
    x0, y0 = wall, H*0.8 - bh - wall*0.9
    il.body(f"M{x0-wall*0.6},{y0} L{x0+bw+wall*0.6},{y0} L{x0+bw},{y0+bh+wall*0.9} L{x0},{y0+bh+wall*0.9} Z")
