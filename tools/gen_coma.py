"""134 コマンダンテ C40 用レザーカバー一式（Creema「コマンダンテカバー」item/20222861＋「ビーンジャーカバー」item/21320484 の写真を見て再現）。
本体の直径は D=61（販売店の表記）。作る前に本体とジャーの周りを紙テープで測って C を差し替える。
tools/ で実行 → ../pat/134.svg と ../data_coma.json
"""
import json, os, sys, math
sys.path.insert(0, os.path.dirname(__file__))
from svgx import T
from svglib import rr

ROOT = os.path.join(os.path.dirname(__file__), "..")
DATE = "2026-11-25"
D = 61.0; t = 1.5
C = round(math.pi * (D + t))          # 革の中心で一周 ≒193
H1, H2 = 90, 50                        # 本体スリーブ／ジャースリーブの高さ（写真の比率から）

s = T(300, 330)
def sleeve(x, y, h, label):
    s.cut(rr(x, y, C, h, 0))
    for yy in range(int(y + 6), int(y + h - 3), 6):
        s.hole(x + 4, yy, 0.9); s.hole(x + C - 4, yy, 0.9)
    s.text(x + C / 2, y + h / 2, label, 0.8, bold=True)
    s.dim(x, y, x + C, y, f"{C}（周＝π×(直径{D:.0f}＋革厚{t})）", -10); s.dim(x + C, y, x + C, y + h, str(h), -12)

sleeve(0, 10, H1, "①本体スリーブ")
s.hole(C * 0.25, 10 + 8, 2.5); s.hole(C * 0.75, 10 + 8, 2.5)
s.text(C * 0.25, 30, "ホック（③の耳）", 0.42, "#8a7a6d"); s.text(C * 0.75, 30, "ホック（③・④）", 0.42, "#8a7a6d")
s.text(C / 2, 10 + H1 - 8, "両端を突き合わせて ×（クロス）でかがる。下端は縫い代なし", 0.45, "#8a7a6d")
sleeve(0, 125, H2, "②ジャースリーブ")
s.sline(4, 125 + H2 - 4, C - 4, 125 + H2 - 4); s.text(C / 2, 125 + H2 - 9, "下端に飾りの一周ステッチ", 0.42, "#8a7a6d")

# ③ 上のディスク（ハンドルの下に敷く）
cx, cy = 45, 245
s.cut(f"M{cx-31},{cy} A31,31 0 0 1 {cx-12},{cy-29.5} L{cx-10},{cy-45} A10,10 0 0 1 {cx+10},{cy-45} L{cx+12},{cy-29.5} A31,31 0 0 1 {cx+31},{cy} "
      f"A31,31 0 0 1 {cx+12},{cy+29.5} L{cx+10},{cy+45} A10,10 0 0 1 {cx-10},{cy+45} L{cx-12},{cy+29.5} A31,31 0 0 1 {cx-31},{cy} Z")
s.hole(cx, cy, 7); s.hole(cx, cy - 46, 2.5); s.hole(cx, cy + 46, 2.5)
s.text(cx + 36, cy - 30, "③上のディスク Ø62", 0.55, bold=True, anchor="start")
s.text(cx + 36, cy - 20, "中央の穴Ø14は軸を通す（実測）", 0.42, "#8a7a6d", anchor="start")
s.text(cx + 36, cy - 11, "耳は下へ折ってスリーブのホックへ", 0.42, "#8a7a6d", anchor="start")
s.dim(cx - 31, cy + 55, cx + 31, cy + 55, "62", 8); s.dim(cx - 31, cy - 55, cx - 31, cy + 55, "110", 12)
s.fold(cx - 12, cy - 29.5, cx + 12, cy - 29.5); s.fold(cx - 12, cy + 29.5, cx + 12, cy + 29.5)

# ④ Y字のハンドル押さえ
yx, yy0 = 150, 210
s.cut(f"M{yx},{yy0+70} L{yx},{yy0+35} L{yx-14},{yy0+5} A7,7 0 0 1 {yx-2},{yy0} L{yx+9},{yy0+24} L{yx+20},{yy0} A7,7 0 0 1 {yx+32},{yy0+5} L{yx+18},{yy0+35} L{yx+18},{yy0+70} A9,9 0 0 1 {yx},{yy0+70} Z")
s.hole(yx + 9, yy0 + 62, 2.5); s.hole(yx - 8, yy0 + 7, 2.5); s.hole(yx + 26, yy0 + 7, 2.5)
s.text(yx + 9, yy0 + 100, "④ハンドル押さえ", 0.5, bold=True)
s.text(yx + 9, yy0 + 109, "2本の先でアームをはさみホック", 0.4, "#8a7a6d")
s.dim(yx - 18, yy0 + 79, yx + 36, yy0 + 79, "54", 6); s.dim(yx + 36, yy0, yx + 36, yy0 + 79, "79", -10)

# ⑤ ベルト
bx = 225
s.cut(rr(bx, 200, 20, 120, 10)); s.text(bx + 10, 196, "⑤ベルト 20×240（途中省略）", 0.45, bold=True)
s.hole(bx + 10, 210, 2.5); s.hole(bx + 10, 310, 2.5)
s.text(bx + 10, 262, "≈", 1.2, "#8a7a6d")
s.note(-26, 342, [f"直径{D:.0f}は仮。本体とジャーの周りを紙テープで測り、①②の長さ＝測った周＋革厚×π（約5）にする",
                  "④⑤はハンドルを外して本体に沿わせて留めるためのパーツ。持ち歩かないなら①②③だけでもいい"], 0.55)
s.save(os.path.join(ROOT, "pat", "134.svg"), "コマンダンテ C40 用カバー一式（本体・ジャー・上ディスク・ハンドル押さえ・ベルト）")

item = dict(no="134", date=DATE, type="財布・小物", name="コマンダンテ C40 用レザーカバー一式",
            src="Creema「コマンダンテカバー」「コマンダンテビーンジャーカバー」を参考に再現（個人製作用）",
            url="https://www.creema.jp/item/20222861/detail",
            photos=[], structure="写真で確認：5つのパーツ。①本体にかぶせる筒（端を突き合わせて側面を×の飾りかがり）②ジャーにかぶせる短い筒（下端に一周ステッチ）③ハンドルの下に敷く丸いディスク（左右の耳を下に折ってスリーブ上部のホックに留める）④Y字のハンドル押さえ（アームをはさんでスリーブのホックに留める）⑤ベルト（本体に巻いて、外したハンドルを沿わせて留める）。どれも縫うのは筒の継ぎ目と飾りだけ。",
            size="本体用 周193×高さ90、ジャー用 周193×高さ50（直径61＝販売店の表記。要実測）",
            spec="プエブロ／ブッテーロ 1.2〜1.5mm、バネホック小 6組", level="★★", status="候補", fav=True,
            memo="元作品 16,500円（ジャーカバー単品 6,800円）。C40とC60でサイズが少し違う（ジャー部分は共通）。",
            pattern="pat/134.svg",
            parts=[["①本体スリーブ", f"{C}×{H1}", "1", "1.2〜1.5mm"], ["②ジャースリーブ", f"{C}×{H2}", "1", "1.2〜1.5mm"],
                   ["③上のディスク", "Ø62＋耳（全長110）", "1", "1.5mm"], ["④ハンドル押さえ（Y字）", "54×79", "1", "1.5mm"],
                   ["⑤ベルト", "20×240", "1", "1.5mm"], ["バネホック", "小", "6組", "-"]],
            patnote=f"写真で立体確認済み（{DATE}）。①本体とジャーの周りを紙テープで測る→①②の長さを決める ②①②の両端に菱目（ピッチ6）を打ち、円筒に丸めて端を突き合わせ、×のクロスステッチでかがる（濡らして本体にかぶせたまま乾かすとぴったり）③③の中央の穴は軸の太さを測って開ける ④ホックは①の上端に2か所（③の耳用・④用）、④⑤の先に。寸法は写真の比率から割り出した推定。",
            reviewed=DATE)
json.dump(item, open(os.path.join(ROOT, "data_coma.json"), "w"), ensure_ascii=False, indent=1)
print(C)
