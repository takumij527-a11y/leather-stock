def fanp(cx, by, bottom, top, h, sag, close=True):
    x1, x2, X1, X2, ty = cx - bottom / 2, cx + bottom / 2, cx - top / 2, cx + top / 2, by - h
    r = (top / 2) ** 2 / (2 * sag) + sag / 2 if sag else 0
    arc = f"A{r:.1f},{r:.1f} 0 0 0 {X1},{ty}" if sag else f"L{X1},{ty}"
    return f"M{x1},{by} L{x2},{by} L{X2},{ty} {arc}" + (" Z" if close else "")


def sector(ax, ay, R, a0, a1):
    """中心(ax,ay)、半径R、角度a0→a1（度、0=右、90=下）の扇形"""
    p = lambda a: (ax + R * math.cos(math.radians(a)), ay + R * math.sin(math.radians(a)))
    (x0, y0), (x1, y1) = p(a0), p(a1)
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f"M{ax},{ay} L{x0:.1f},{y0:.1f} A{R},{R} 0 {large} 1 {x1:.1f},{y1:.1f} Z", p


def item(no, size, spec, level, parts, patnote, structure=None):
    out[no] = dict(size=size, spec=spec, level=level, parts=parts, patnote=OK + patnote, pattern=f"pat/{no}.svg", reviewed=DATE)
    if structure: out[no]["structure"] = structure


